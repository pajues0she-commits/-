def pictograms_for_codes(h_codes):
    """H-code 목록으로부터 GHS 그림문자 코드 목록을 추론한다 (GHS01~09 순서)."""
    found = []
    codes = set(h_codes)
    for pic in sorted(_PICTOGRAM_RULES):
        if codes & _PICTOGRAM_RULES[pic]:
            found.append(pic)
    # GHS 우선순위 규칙: 해골(GHS06)이 있으면 느낌표(GHS07)의 급성독성 표시는 생략,
    # 부식성(GHS05)이 있으면 피부/눈 자극의 느낌표는 생략
    if "GHS06" in found and "GHS07" in found:
        only_irritant = codes & _PICTOGRAM_RULES["GHS07"] <= {"H302", "H312", "H332"}
        if only_irritant:
            found.remove("GHS07")
    if "GHS05" in found and "GHS07" in found:
        only_skin_eye = codes & _PICTOGRAM_RULES["GHS07"] <= {"H315", "H319"}
        if only_skin_eye:
            found.remove("GHS07")
    return found


def signal_word_for_codes(h_codes):
    """H-code 목록으로부터 신호어를 추론한다."""
    codes = set(h_codes)
    if codes & _DANGER_CODES:
        return "위험"
    if codes & set(H_STATEMENTS):
        return "경고"
    return ""
