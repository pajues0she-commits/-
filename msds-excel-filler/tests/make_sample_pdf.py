def make(path, text=SAMPLE):
    pdfmetrics.registerFont(UnicodeCIDFont("HYGothic-Medium"))
    c = canvas.Canvas(path, pagesize=A4)
    width, height = A4
    y = height - 50
    c.setFont("HYGothic-Medium", 10)
    for line in text.splitlines():
        if y < 50:
            c.showPage()
            c.setFont("HYGothic-Medium", 10)
            y = height - 50
        c.drawString(40, y, line)
        y -= 14
    c.save()
    print("wrote", path)


